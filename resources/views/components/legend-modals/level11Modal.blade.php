            <h6 class="fw-bold"><b>Overview</b></h6>
            <p class="text-justify">Community health centers are the lowest tier of MOH facilities. The MOH strategy lists five: Faleolo, Lufilufi and Sa&rsquo;anapu Health Centres on Upolu, and Vaipouli Health Centre on Savai&rsquo;i. Faleolo Health Centre was established to handle emergencies at Faleolo International Airport. Lufilufi Health Centre provides 24-hour general outpatient care and refers patients to TTM within five hours of monitoring if needed; because of bed shortages at the main hospital, some patients stay at Lufilufi for up to 24 hours and are recorded as inpatients. On Upolu, MOH also runs Urban Community Services, and health centers provide family planning alongside the district hospitals.</p>
            <p class="text-justify"><strong>Note:</strong> &ldquo;Community Health Center&rdquo; is a statutory facility type under Section 5(1)(d)(i) of the Ministry of Health Act. MOH reports refer to Upolu as having &ldquo;3 District Hospitals and 3 Health Centers.&rdquo; Record these as &ldquo;Community Health Center &mdash; public (MOH).&rdquo;</p>
            <h6 class="fw-bold"><b>Role</b></h6>
            <ul>
                <li>Provide primary care, outpatient and emergency first response, and public health programs</li>
                <li>Refer patients to the nearest district hospital or main hospital.</li>
            </ul>
