            <h6 class="fw-bold"><b>Overview</b></h6>
            <p class="text-justify">Tupua Tamasese Meaole Hospital (TTM Hospital) at Moto&rsquo;otua, Apia, on Upolu is Samoa&rsquo;s national referral hospital. MOH describes it as &ldquo;the national referral base providing overarching clinical leadership for all health facilities in Samoa,&rdquo; providing &ldquo;outpatient and inpatient clinical services at secondary and limited tertiary level&rdquo; (MOH Annual Report 2023&ndash;2024). A new TTM Hospital building was constructed between 2006 and 2017 as part of public health sector reforms.</p>
            <p class="text-justify"><strong>Note:</strong> In law, TTM falls under &ldquo;National Hospitals&rdquo; in Section 5(1)(d)(i) of the Ministry of Health Act. Record it as &ldquo;National Referral Hospital &mdash; public (MOH), secondary and limited tertiary care.&rdquo; Care not available in Samoa is referred overseas under the Overseas Treatment Scheme.</p>
            <h6 class="fw-bold"><b>Role</b></h6>
            <ul>
                <li>Receive referrals from MTII Hospital, all district hospitals and community health centers</li>
                <li>Provide clinical leadership for all health facilities in Samoa</li>
                <li>Coordinate visiting specialist teams and overseas referrals for treatment.</li>
            </ul>
            <h6 class="fw-bold"><b>Clinical Service</b></h6>
            <p><strong>Core Capability Areas</strong></p>
            <ul>
                <li>Surgical, medical, pediatric, intensive care, obstetrics and gynecology, maternal health and mental health services (MOH Annual Report 2023&ndash;2024)</li>
            </ul>
            <p><strong>Diagnostic &amp; Support Infrastructure</strong></p>
            <ul>
                <li>National laboratory and pathology services (biochemistry, hematology, microbiology, serology, histology and cytology, blood bank), which also serve private providers; medical imaging and radiology; dental and oral health; hospital pharmacy</li>
            </ul>
            <p><strong>Typical Bed Capacity</strong></p>
            <ul>
                <li>About 200 beds (NHS Annual Report 2015&ndash;2016)</li>
            </ul>
