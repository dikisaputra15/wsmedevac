            <h6 class="fw-bold"><b>Overview</b></h6>
            <p class="text-justify">District hospitals are rural facilities managed by MOH&rsquo;s Rural District Hospitals and Community Health division. MOH&rsquo;s Health Facilities and Capital Assets Management Strategy 2022/23&ndash;2026/27 lists seven district hospitals:</p>
            <ul>
                <li>Upolu: Leulumoega, Lalomanu and Poutasi District Hospitals</li>
                <li>Savai&rsquo;i: Foailalo, Safotu, Satupaitea and Sataua District Hospitals</li>
            </ul>
            <p class="text-justify">All district hospitals provide 24-hour services, seven days a week, with doctors and nurses on 12-hour shifts. They admit inpatients, run antenatal care and family planning, carry out school health visits and provide home care, intermediate care and palliative care. MOH states that services carried out in the main hospital are also performed in the district hospitals, except essential services that require transfer to the main hospital.</p>
            <p class="text-justify"><strong>Note:</strong> &ldquo;District Hospital&rdquo; is a statutory facility type under Section 5(1)(d)(i) of the Ministry of Health Act, prescribed by Ministerial Notice; we did not locate the Notice itself. The same MOH strategy also refers to &ldquo;10 district hospitals and 2 health centres&rdquo; transferred from the NHS in 2019, which does not match its own facility list (7 district hospitals and 5 health centers). Record facilities by the name the Ministry uses, and check the Ministerial Notice for the authoritative list.</p>
            <h6 class="fw-bold"><b>Role</b></h6>
            <ul>
                <li>Provide 24-hour emergency, outpatient and inpatient care to rural districts</li>
                <li>Deliver antenatal care, family planning and community health programs</li>
                <li>Refer and transfer patients to TTM or MTII Hospital for intensive or specialized care.</li>
            </ul>
            <h6 class="fw-bold"><b>Clinical Service</b></h6>
